import { describe, expect, it } from "vitest";
import { plural } from "./plural";

const F = ["символ", "символа", "символов"] as const;

describe("plural", () => {
  it.each([
    [0, "символов"],
    [1, "символ"],
    [2, "символа"],
    [4, "символа"],
    [5, "символов"],
    [11, "символов"],
    [12, "символов"],
    [14, "символов"],
    [21, "символ"],
    [22, "символа"],
    [100, "символов"],
    [101, "символ"],
    [111, "символов"],
    [1002, "символа"],
  ])("%i → %s", (n, expected) => {
    expect(plural(n, F)).toBe(expected);
  });
});
